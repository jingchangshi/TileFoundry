#!/usr/bin/env bash
# Record what this baseline actually ran on.
#
# A result is only as meaningful as the stack it was produced on, and this host
# is shared and mutable: the tree can carry uncommitted edits, the venv can be
# changed by another install, and CANN is a beta. A number without this file is
# a number nobody can reproduce or even interpret.
#
# Two warnings this records rather than hides:
#
#   * dirty state. A tree with uncommitted changes is not a commit, so the
#     recorded SHA does NOT identify the source that ran. The dirty flag and the
#     changed paths are written next to the SHA so that gap is visible.
#   * isolation limits. Passing three device nodes is not security isolation and
#     not complete manager isolation. See the manifest body.
#
# Exit codes: 0 manifest written, 2 could not write it.
set -uo pipefail

HOST_REPO="${TF_REPO:-/home/s00653124/workspace/TileFoundry}"
VENV="${TF_VENV:-/home/s00653124/workspace/tfpy312}"
CANN_ROOT="${CANN_ROOT:-/data/pri/cann-9.2.0}"
CONTAINER="${TF_CONTAINER:-tf-ascend950pr}"
OUT="${1:-/home/s00653124/workspace/TileFoundry_Ascend950PR_AgentTeam/artifacts/run02/p0/container/manifest.txt}"

log() { printf 'manifest.sh: %s\n' "$*" >&2; }
die() { log "$*"; exit 2; }

command -v git >/dev/null 2>&1 || die "git not found"
[ -d "$HOST_REPO/.git" ] || die "not a git repo: $HOST_REPO"
mkdir -p "$(dirname -- "$OUT")" || die "cannot create $(dirname -- "$OUT")"

emit() { printf '%s\n' "$@" >> "$OUT"; }
DIRTY_FLAG="$(dirname -- "$OUT")/.manifest.dirty.$"
trap 'rm -f "$DIRTY_FLAG"' EXIT
: > "$OUT" || die "cannot write $OUT"

emit "# Baseline manifest";
emit "# Generated by docker/ascend950pr/manifest.sh";
emit "generated: $(date -Is)"
emit "host: $(hostname)"
emit ""

emit "## Source";
emit "repo: $HOST_REPO"
DIRTY_STATE="unknown"
( cd "$HOST_REPO" || exit 2
  emit "branch: $(git rev-parse --abbrev-ref HEAD)"
  emit "commit: $(git rev-parse HEAD)"
  dirty="$(git status --porcelain)"
  if [ -n "$dirty" ]; then
    emit "dirty: YES"
    emit "dirty_note: the commit above does NOT identify the source that ran;"
    emit "dirty_note: the working tree carried the changes below at capture time."
    emit "dirty_paths:"
    printf '%s\n' "$dirty" | sed 's/^/  /' | while IFS= read -r line; do emit "$line"; done
  else
    emit "dirty: no"
  fi
  emit "tool_commit_tools: $(git log -1 --format=%H -- examples/rmsnorm_950pr/tools 2>/dev/null || echo unknown)"
  emit "tool_commit_docker: $(git log -1 --format=%H -- docker/ascend950pr 2>/dev/null || echo unknown)"
  # The verdict below must see this; a subshell would swallow it, which is the
  # same masking class this manifest exists to expose.
  printf '%s\n' "$dirty" > "$DIRTY_FLAG"
) || die "git queries failed"
DIRTY_STATE="$(cat "$DIRTY_FLAG" 2>/dev/null || echo unknown)"
emit ""

emit "## Python environment"
emit "venv: $VENV"
if [ -x "$VENV/bin/python" ]; then
  emit "python: $("$VENV/bin/python" --version 2>&1)"
  emit "python_executable: $(readlink -f "$VENV/bin/python" 2>/dev/null || echo unknown)"
  # This venv was created by uv and has NO pip module. That is deliberate, not
  # broken. Record the snapshot through whichever tool exists and say which one
  # produced it: an inventory whose provenance is unknown cannot be compared.
  if "$VENV/bin/python" -m pip --version >/dev/null 2>&1; then
    emit "deps_tool: pip freeze"
    emit "deps:"
    "$VENV/bin/python" -m pip freeze 2>/dev/null | sort | sed 's/^/  /' | while IFS= read -r line; do emit "$line"; done
  elif command -v uv >/dev/null 2>&1; then
    emit "deps_tool: uv pip list"
    emit "deps:"
    uv pip list --python "$VENV/bin/python" 2>/dev/null | sort | sed 's/^/  /' | while IFS= read -r line; do emit "$line"; done
  else
    emit "deps: UNAVAILABLE -- neither pip nor uv can inventory this venv"
  fi
  tf_ver="$(PYTHONPATH="$HOST_REPO/src:$HOST_REPO/targets/ascend" "$VENV/bin/python" -c 'import tilefoundry; print(getattr(tilefoundry, "__version__", "no-version"))' 2>&1)"
  emit "tilefoundry_import: $tf_ver"
else
  emit "python: UNAVAILABLE at $VENV/bin/python"
fi
emit ""

emit "## CANN"
if [ -e "$CANN_ROOT" ]; then
  emit "cann_root: $CANN_ROOT"
  # The EFFECTIVE version is what set_env.sh selects, which need not be the
  # directory name. Recording only the path would hide a beta behind a path.
  eff="$(
    set +u
    # shellcheck disable=SC1090
    . "$CANN_ROOT/cann/set_env.sh" >/dev/null 2>&1
    printf '%s\n' "${ASCEND_TOOLKIT_HOME:-<unset>}"
  )"
  emit "cann_effective_ascend_toolkit_home: ${eff:-<unset>}"
  if [ -n "${eff:-}" ] && [ "$eff" != "<unset>" ] && [ -e "$eff/version.cfg" ]; then
    emit "cann_version_cfg: $(head -3 "$eff/version.cfg" 2>/dev/null | tr '\n' ' ')"
  fi
  if [ -e "$CANN_ROOT/cann/version.cfg" ]; then
    emit "cann_root_version_cfg: $(head -3 "$CANN_ROOT/cann/version.cfg" 2>/dev/null | tr '\n' ' ')"
  fi
else
  emit "cann_root: MISSING at $CANN_ROOT"
fi

# Driver version: read the host driver, never modify it.
driver="/usr/local/Ascend/driver"
if [ -e "$driver/version.info" ]; then
  emit "driver_version_info: $(head -3 "$driver/version.info" 2>/dev/null | tr '\n' ' ')"
elif [ -e "$driver" ]; then
  emit "driver: $driver present; version.info absent"
else
  emit "driver: MISSING at $driver"
fi
emit ""

emit "## Kernel"
emit "kernel_release: $(uname -r)"
emit "kernel_build: $(uname -v)"
if [ -r /proc/version ]; then emit "proc_version: $(cat /proc/version)"; fi
emit ""

emit "## Container"
if command -v docker >/dev/null 2>&1; then
  cid="$(docker inspect "$CONTAINER" --format '{{.Id}}' 2>/dev/null || true)"
  if [ -n "$cid" ]; then
    emit "container: $CONTAINER"
    emit "container_id: $cid"
    emit "image: $(docker inspect "$CONTAINER" --format '{{.Config.Image}}' 2>/dev/null)"
    emit "image_id: $(docker inspect "$CONTAINER" --format '{{.Image}}' 2>/dev/null)"
    emit "privileged: $(docker inspect "$CONTAINER" --format '{{.HostConfig.Privileged}}' 2>/dev/null)"
    emit "devices:"
    docker inspect "$CONTAINER" --format '{{range .HostConfig.Devices}}  {{.PathOnHost}} -> {{.PathInContainer}}{{"\n"}}{{end}}' 2>/dev/null | sed '/^$/d' | while IFS= read -r line; do emit "$line"; done
  else
    emit "container: $CONTAINER NOT FOUND"
  fi
else
  emit "docker: not available"
fi
emit ""

emit "## Isolation limits -- read this before quoting a result"
emit "devicenode_visibility: NOT security isolation."
emit "  Passing /dev/davinci0 narrows what docker exposes. It does not sandbox"
emit "  the NPU: the container is unprivileged but shares the host driver, and"
emit "  the manager node /dev/davinci_manager is passed for the runtime to work."
emit "  Any container with the manager node can address more than device 0 at"
emit "  the driver level. Treat this as accident prevention, not containment."
emit "npu_runtime: NOT PROVEN."
emit "  torch_npu / the CANN runtime have not been exercised from inside this"
emit "  container. Every check so far is CPU-side analysis and finalize. That"
emit "  hardware execution works here is an assumption until a device run does."
emit "shared_tenant: timings are PROVISIONAL."
emit "  Other tenants run on both NPUs. Numerics are unaffected; latency and"
emit "  throughput numbers are not reproducible and must be labelled so."
emit ""

emit "## Verdict"
if [ "$DIRTY_STATE" = "unknown" ]; then
  emit "reproducible_from_commit: UNKNOWN -- the dirty check did not report"
elif [ -n "$DIRTY_STATE" ]; then
  emit "reproducible_from_commit: NO -- working tree was dirty at capture"
  emit "  The recorded commit does NOT identify the source that ran."
else
  emit "reproducible_from_commit: the recorded commit matches the tree"
fi

log "wrote $OUT ($(wc -l < "$OUT") lines)"
exit 0