"""Materialize a Resolved TF TIR from the ResolvedPlan.

Address, slot and guard are all rewritten with the task's own logical iteration
t_j = q - stage_j. The output is a stable, parseable text form; the event list
returned here is the source for the verifier, which re-extracts events from the
printed text (not from these objects).
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Event:
    seq: int
    kind: str      # WAIT | SET | MTE2 | MTE3 | VECTOR | GUARD | DRAIN
    channel: str
    slot: int
    gen: int
    task: str
    t: int


def _slot(t, V):
    return t % V


def channel_names(plan) -> dict:
    """Map the DEMO's ring roles onto the channels the plan actually derived.

    WHY THIS IS NOT A HARDCODED LIST ANY MORE. This module emits a three-task demo program
    (x_load -> main_vf -> y_store) as text TIR, and it used to spell the six channel names
    literally: x_ready, x_free, y_ready, y_free. Those names were RMSNorm's, and after the
    obligation derivation became a function of the program (schedule/sync.py) they no longer
    exist -- so a literal lookup would either crash or, worse, emit a program naming channels
    the allocator never assigned.

    The roles are looked up by what they ORDER instead: which task produces, which consumes,
    which event kind. A role with no derived channel is a refusal naming the missing edge,
    never a silently invented name.
    """
    by_pair = {}
    for obligation in plan.get("obligations") or ():
        key = (obligation.get("producer"), obligation.get("consumer"),
               "free" if "free" in str(obligation.get("channel", "")) else "ready")
        by_pair.setdefault(key, str(obligation.get("channel")))

    roles = {
        "x_ready": ("x_load", "main_vf", "ready"),
        "x_free": ("main_vf", "x_load", "free"),
        "y_ready": ("main_vf", "y_store", "ready"),
        "y_free": ("y_store", "main_vf", "free"),
    }
    names = {}
    missing = []
    for role, key in roles.items():
        channel = by_pair.get(key)
        if channel is None:
            missing.append("%s (needs a %s edge %s->%s)" % (role, key[2], key[0], key[1]))
            continue
        names[role] = channel
    if missing:
        raise KeyError("the plan derived no channel for: " + "; ".join(missing))
    return names


def iter_events(problem, plan, steps: int):
    Vx = problem.policy["x_versions"]; Vy = problem.policy["y_versions"]
    names = channel_names(plan)
    st = plan["stages"]
    sl, sv, so = st["x_load"], st["main_vf"], st["y_store"]
    S = problem.policy["requested_num_stages"]
    total_q = steps + (S - 1)
    ev = []
    seq = 0

    def add(kind, channel, slot, gen, task, t):
        nonlocal seq
        ev.append(Event(seq, kind, channel, slot, gen, task, t)); seq += 1

    for q in range(total_q):
        # x_load at stage sl
        t = q - sl
        if 0 <= t < steps:
            add("GUARD", "x_load", _slot(t, Vx), t, "x_load", t)
            if t >= Vx:
                add("WAIT", names["x_free"], _slot(t, Vx), t, "x_load", t)
            add("MTE2", "x_load", _slot(t, Vx), t, "x_load", t)
            add("SET", names["x_ready"], _slot(t, Vx), t, "x_load", t)
        # main_vf at stage sv
        t = q - sv
        if 0 <= t < steps:
            add("WAIT", names["x_ready"], _slot(t, Vx), t, "main_vf", t)
            if t >= Vy:
                add("WAIT", names["y_free"], _slot(t, Vy), t, "main_vf", t)
            add("VECTOR", "main_vf", _slot(t, Vy), t, "main_vf", t)
            add("SET", names["x_free"], _slot(t, Vx), t, "main_vf", t)
            add("SET", names["y_ready"], _slot(t, Vy), t, "main_vf", t)
        # y_store at stage so
        t = q - so
        if 0 <= t < steps:
            add("WAIT", names["y_ready"], _slot(t, Vy), t, "y_store", t)
            add("MTE3", "y_store", _slot(t, Vy), t, "y_store", t)
            add("SET", names["y_free"], _slot(t, Vy), t, "y_store", t)
    add("DRAIN", "drain", 0, total_q, "drain", steps)
    return ev


def materialize_tir(problem, plan, steps: int):
    """Return (tir_text, events, header_dict)."""
    c = problem.policy
    Vx = c["x_versions"]; Vy = c["y_versions"]; S = c["requested_num_stages"]
    st = plan["stages"]
    ev = iter_events(problem, plan, steps)
    hdr = {
        "problem_id": problem.problem_id, "source_digest": problem.source_digest,
        "stages": st, "ii": plan["ii"], "num_stages_requested": S,
        "x_versions": Vx, "y_versions": Vy, "flag_pool": plan["flag_pool"],
        "effective_offset": c["effective_offset"],
    }
    lines = []
    lines.append("# Resolved TF TIR (Ascend950PR AIV), generated by tilefoundry_ascend")
    lines.append(f"# problem_id={problem.problem_id} source_digest={problem.source_digest}")
    lines.append(f"# requested_num_stages={S} x_versions={Vx} y_versions={Vy} ii={plan['ii']} effective_offset={c['effective_offset']}")
    lines.append(f"def rmsnorm_resolved(steps):")
    lines.append(f"  # AIV mesh layout = core_count; per-core steps = {steps}")
    lines.append(f"  for q in range(steps + {S - 1}):")
    for e in ev:
        if e.kind == "GUARD":
            lines.append(f"    # t_{e.task} = q - {st.get(e.task,0)} ; guard 0 <= t < steps")
        elif e.kind == "WAIT":
            lines.append(f"    wait_flag {e.channel}[{e.slot}] gen={e.gen} flag={plan['flag_pool'][e.channel]}  # {e.task} t={e.t}")
        elif e.kind == "SET":
            lines.append(f"    set_flag {e.channel}[{e.slot}] gen={e.gen} flag={plan['flag_pool'][e.channel]}  # {e.task} t={e.t}")
        elif e.kind == "MTE2":
            lines.append(f"    mte2 {e.task} slot={e.slot} t={e.t}  # GM->UB window (t*rows*d)")
        elif e.kind == "MTE3":
            lines.append(f"    mte3 {e.task} slot={e.slot} t={e.t}  # UB->GM window (t*rows*d)")
        elif e.kind == "VECTOR":
            lines.append(f"    simdvf main_compute slot={e.slot} t={e.t}  # 4-way accum + 6 vcadd + scale")
        elif e.kind == "DRAIN":
            lines.append(f"  drain()  # final visibility barrier")
    text = "\n".join(lines)
    return text, ev, hdr


__all__ = ["Event", "channel_names", "iter_events", "materialize_tir"]
